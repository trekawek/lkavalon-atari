"""Exercise the real game Makefiles without running the Atari compiler.

Set MAKE_UNDER_TEST to a GNU make executable, including macOS's make 3.81.
Builders are replaced by a small recorder; their dependency discovery and
multi-output write order match the production tools.
"""

from collections import Counter
import json
import os
from pathlib import Path
import shlex
import shutil
import subprocess
import sys
import tempfile
import time
import unittest


ROOT = Path(__file__).resolve().parents[1]
GAMES = ("ad2044", "klatwa", "wladcy-ciemnosci")
REPORT = "build/program/compile-report.json"
SCAN_ERRORS = {
    "assets": "Cannot read authored content dependencies",
    "forth": "Cannot read embedded Forth asset dependencies",
    "compiler": "Cannot read fig-Forth source dependencies",
}

BUILDER = r'''
import json
import os
from pathlib import Path
import sys
import time

script, *args = sys.argv[1:]
tool = Path(script).name
root = Path.cwd()
game = root.name
ad = game == "ad2044"
program = "ad2044-side1.atr" if ad else game + ".atr"

def write(path):
    path = root / path
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("generated by " + tool + "\n")

def event(name):
    with (root / "events.jsonl").open("a") as output:
        output.write(json.dumps(name) + "\n")
    # Expose duplicate producers when make schedules independent targets.
    time.sleep(0.05)

def failure(name):
    if os.environ.get("FAIL_BUILDER") == name:
        print("intentional failure after primary write: " + name, file=sys.stderr)
        sys.exit(9)

if "--dependencies" in args:
    scan, dependency = {
        "content.py": ("assets", "inputs/assets.txt"),
        "gam_content.py": ("assets", "inputs/assets.txt"),
        "forth_assets.py": ("forth", "inputs/forth.txt"),
        "build_figforth.py": ("compiler", "../util/figforth/source.txt"),
    }[tool]
    # Fail after printing a plausible dependency, as a partially completed
    # scanner can do. Nonempty stdout alone must never mean success.
    print(dependency)
    if os.environ.get("FAIL_SCAN") == scan:
        print("intentional dependency failure: " + scan, file=sys.stderr)
        sys.exit(7)
elif "--empty-disk" in args:
    event("empty")
    write(args[args.index("--empty-disk") + 1])
elif tool == "build_figforth.py":
    event("figforth")
    write(args[args.index("--output") + 1])
elif tool == "compile.py":
    event("compile")
    write("build/program/" + program)
    failure("compile")
    write("build/program/compile-report.json")
elif tool == "pack_sources.py":
    event("sources")
    write("build/sources.atr")
elif tool in ("content.py", "gam_content.py"):
    if "--link" in args:
        event("link")
        write("build/" + program)
    else:
        event("content")
        write("build/assets-side1.atr" if ad else "build/assets.atr")
        failure("content")
        if ad:
            write("build/ad2044-side2.atr")
else:
    raise SystemExit("Unexpected builder invocation: " + repr(sys.argv))
'''


class MakefileTests(unittest.TestCase):
    def fixture(self, game):
        temporary = tempfile.TemporaryDirectory(prefix="forth-make-")
        self.addCleanup(temporary.cleanup)
        repository = Path(temporary.name)
        root = repository / game
        (root / "src").mkdir(parents=True)
        (root / "inputs").mkdir()
        shutil.copyfile(ROOT / game / "Makefile", root / "Makefile")
        # Keep all real prerequisite names without copying source/data assets.
        for directory in ("util", "ad2044/tools", game + "/tools"):
            for source in (ROOT / directory).glob("*.py"):
                path = repository / source.relative_to(ROOT)
                path.parent.mkdir(parents=True, exist_ok=True)
                path.touch()
        for filename in ("src/game.fth", "sources.json", "inputs/assets.txt",
                         "inputs/forth.txt", "../util/figforth/source.txt"):
            path = root / filename
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text("fixture\n")
        stub = repository / "builder.py"
        stub.write_text(BUILDER)
        # Production inputs are older than every output, even with the
        # one-second timestamp precision of older make/filesystem combinations.
        old = time.time() - 60
        for path in repository.rglob("*"):
            if path.is_file():
                os.utime(path, (old, old))
        return root

    def make(self, root, *goals, fail_scan=None, fail_builder=None, python=None,
             succeeds=True):
        command = shlex.split(os.environ.get("MAKE_UNDER_TEST", "make"))
        if python is None:
            python = shlex.quote(sys.executable) + " " + shlex.quote(str(root.parent / "builder.py"))
        command += ["--no-print-directory", "-j4", "PYTHON=" + python, *goals]
        environment = os.environ.copy()
        for name in ("MAKEFLAGS", "MFLAGS", "GNUMAKEFLAGS", "MAKELEVEL", "FAIL_SCAN", "FAIL_BUILDER"):
            environment.pop(name, None)
        if fail_scan:
            environment["FAIL_SCAN"] = fail_scan
        if fail_builder:
            environment["FAIL_BUILDER"] = fail_builder
        result = subprocess.run(command, cwd=root, env=environment, text=True,
                                capture_output=True, timeout=30)
        output = result.stdout + result.stderr
        if succeeds:
            self.assertEqual(result.returncode, 0, output)
        else:
            self.assertNotEqual(result.returncode, 0, output)
        return result

    def events(self, root):
        path = root / "events.jsonl"
        if not path.exists():
            return Counter()
        result = Counter(json.loads(line) for line in path.read_text().splitlines())
        path.unlink()
        return result

    def outputs(self, game):
        program = "ad2044-side1.atr" if game == "ad2044" else game + ".atr"
        result = ["build/" + program, "build/program/" + program, REPORT,
                  "build/sources.atr", "build/figforth.atr", "build/empty.atr"]
        result += (["build/assets-side1.atr", "build/ad2044-side2.atr"]
                   if game == "ad2044" else ["build/assets.atr"])
        return result

    def assert_outputs(self, root):
        for filename in self.outputs(root.name):
            self.assertTrue((root / filename).is_file(), filename)

    def test_parallel_default_and_explicit_outputs_build_once_then_do_nothing(self):
        expected = Counter({name: 1 for name in ("content", "compile", "sources", "figforth", "empty", "link")})
        for game in GAMES:
            for goals in ((), ("all", REPORT)):
                with self.subTest(game=game, goals=goals):
                    root = self.fixture(game)
                    self.make(root, *goals)
                    self.assertEqual(self.events(root), expected)
                    self.assert_outputs(root)
                    self.make(root, "all", REPORT)
                    self.assertFalse(self.events(root), "Cached build invoked a producer or linker")

    def test_deleted_primary_or_companion_rebuilds_its_group_once(self):
        for game in GAMES:
            with self.subTest(game=game):
                root = self.fixture(game)
                self.make(root)
                self.events(root)
                program = "ad2044-side1.atr" if game == "ad2044" else game + ".atr"
                cases = [(REPORT, "compile"), ("build/program/" + program, "compile")]
                if game == "ad2044":
                    cases += [("build/ad2044-side2.atr", "content"), ("build/assets-side1.atr", "content")]
                for filename, producer in cases:
                    with self.subTest(missing=filename):
                        time.sleep(1.05)
                        (root / filename).unlink()
                        self.make(root, "all", REPORT)
                        self.assertEqual(self.events(root), Counter({producer: 1, "link": 1}))
                        self.assert_outputs(root)
                        self.make(root, "all", REPORT)
                        self.assertFalse(self.events(root))

    def test_source_and_asset_edits_rebuild_only_affected_outputs(self):
        for game in GAMES:
            with self.subTest(game=game):
                root = self.fixture(game)
                self.make(root)
                self.events(root)
                for filename, expected in (("inputs/assets.txt", {"content": 1, "link": 1}),
                                           ("src/game.fth", {"compile": 1, "sources": 1, "link": 1})):
                    with self.subTest(edited=filename):
                        time.sleep(1.05)
                        (root / filename).write_text("edited\n")
                        self.make(root, "all", REPORT)
                        self.assertEqual(self.events(root), Counter(expected))

    def test_all_dependency_failures_reject_partial_stdout_and_keep_stderr(self):
        for game in GAMES:
            root = self.fixture(game)
            for scan, message in SCAN_ERRORS.items():
                with self.subTest(game=game, scan=scan):
                    result = self.make(root, fail_scan=scan, succeeds=False)
                    self.assertIn("intentional dependency failure: " + scan, result.stderr)
                    self.assertIn(message, result.stderr)
                    self.assertFalse(self.events(root))

    def test_failed_multi_output_producer_cannot_leave_a_fresh_primary(self):
        for game, producer in [(game, "compile") for game in GAMES] + [("ad2044", "content")]:
            with self.subTest(game=game, producer=producer):
                root = self.fixture(game)
                primary = ("build/assets-side1.atr" if producer == "content" else
                           "build/program/" + ("ad2044-side1.atr" if game == "ad2044" else game + ".atr"))
                result = self.make(root, "all", REPORT, fail_builder=producer, succeeds=False)
                self.assertIn("intentional failure after primary write", result.stderr)
                self.assertFalse((root / primary).exists(), "Failed producer's primary was not deleted")
                self.events(root)
                self.make(root, "all", REPORT)
                self.assertEqual(self.events(root)[producer], 1)
                self.assert_outputs(root)

    def test_clean_does_not_require_python_or_dependency_discovery(self):
        for game in GAMES:
            with self.subTest(game=game):
                root = self.fixture(game)
                (root / "build").mkdir()
                (root / "build/stale.atr").write_text("stale\n")
                self.make(root, "clean", python=str(root / "missing-python"))
                self.assertFalse((root / "build").exists())
                self.assertFalse(self.events(root))


if __name__ == "__main__":
    unittest.main()
